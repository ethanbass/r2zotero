#' r -> Zotero
#'
#' Send citations from the \code{\link{citation}} function directly to Zotero
#' library through the Zotero JSON web API.
#'
#' As with Zotero browser plugins, the Zotero desktop application must be
#' running for the function to work.
#'
#' With `skip_duplicates = TRUE`, r2zotero reads the library through
#' Zotero's local API. Turn it on under *Settings > Advanced > Allow other
#' applications on this computer to communicate with Zotero*. A citation counts
#' as a duplicate if an item of the same type has the same title and year,
#' ignoring case, punctuation and formatting. Only My Library is checked, so
#' duplicates aren't detected if a group library is selected in Zotero.
#'
#' @md
#' @importFrom utils citation installed.packages
#' @param pkg A character vector of package names, or a `bibentry` object such
#' as one returned by [citation()].
#' Base packages such as stats and utils share R's citation, which is imported
#' once. Packages that aren't installed are skipped with a warning.
#' @param manual_as_document Whether to export \code{MANUAL} bibtex entries as
#' a \code{document} rather than \code{software}. Defaults to \code{FALSE}.
#' @param skip_duplicates Whether to skip citations already in the Zotero
#' library. Defaults to `FALSE`.
#' @param verbose Whether to print verbose output to console. Defaults to
#' \code{TRUE}.
#' @author Ethan Bass
#' @return Invisibly, a list with one element per citation entry: the
#' [httr::response] from Zotero, or `NULL` if the entry was skipped as a
#' duplicate.
#' @section Side effects:
#' Imports the citations generated by \code{citation} to a local Zotero library.
#' @examplesIf interactive()
#' ## send package references to Zotero
#' r2zotero("foreign")
#' r2zotero("lattice")
#'
#' ## cite every attached package
#' r2zotero(names(sessionInfo()$otherPkgs))
#' @export

r2zotero <- function(pkg = "base", manual_as_document = FALSE,
                     skip_duplicates = FALSE, verbose = TRUE) {
  if (inherits(pkg, "bibentry")){
    cits <- list(pkg)
    names(cits) <- if (is.null(attr(pkg, "package"))) "" else attr(pkg, "package")
  } else if (is.character(pkg)){
    cits <- get_citations(pkg)
  } else{
    stop("Please provide either package names or a `bibentry` object to the `pkg` argument.")
  }
  if (length(cits) == 0) return(invisible(list()))
  zotero_is_running <- zotero_running()
  if (!zotero_is_running){
    stop("Unable to communicate with the Zotero desktop application. Please make sure Zotero is open and try again.")
  }
  get_zotero_schema(verbose = verbose)
  entries <- unlist(Map(function(cit, pkg){
    lapply(cit, function(ct){
      label <- pkg
      if (!nzchar(label)){
        label <- c(gsub("[{}]", "", ct$title), "citation")[1]
        if (nchar(label) > 40) label <- paste0(substr(label, 1, 40), "...")
      }
      item <- tryCatch(bibentry_to_zotero(ct, manual_as_document = manual_as_document),
                       error = function(e){
                         warning(sprintf("Skipping %s: %s", label, conditionMessage(e)),
                                 call. = FALSE)
                         NULL
                       })
      list(label = label, cit = ct, item = item)
    })
  }, cits, names(cits)), recursive = FALSE, use.names = FALSE)
  entries <- Filter(function(e) !is.null(e$item), entries)
  library_keys <- NULL
  if (skip_duplicates){
    item_types <- unique(vapply(entries, function(e) e$item$itemType, character(1)))
    library_keys <- tryCatch(get_library_keys(item_types), error = function(e){
      warning(sprintf("Can't read the Zotero library to check for duplicates (%s). Turn on Zotero's local API (see ?r2zotero) or set `skip_duplicates = FALSE`.",
                      conditionMessage(e)), call. = FALSE)
      NULL
    })
  }
  responses <- vector("list", length(entries))
  for (k in seq_along(entries)){
    label <- entries[[k]]$label
    ct <- entries[[k]]$cit
    zot_item <- entries[[k]]$item
    key <- item_key(zot_item$itemType, zot_item$title, zot_item$date)
    if (skip_duplicates && !is.na(key) && key %in% library_keys){
      if (verbose)
        message(sprintf("%s is already in Zotero library; skipping", label))
      next
    }
    autogenerated <- !is.null(ct$footer) && grepl("auto-generated", ct$footer)
      if (verbose && autogenerated){
        warning(sprintf("%s is autogenerated. Proceed with caution.", label), immediate. = TRUE)
      }
    response <- save_item(zot_item)
    status <- httr::status_code(response)
    if (status == 201){
      if (skip_duplicates) library_keys <- c(library_keys, key)
      if (verbose)
        message(sprintf("%s successfully imported to Zotero library", label))
    } else {
      warning(sprintf("Failed to import %s to Zotero library (HTTP %s).", label, status),
              call. = FALSE)
    }
    responses[k] <- list(response)
  }
  invisible(responses)
}

#' Get citations for packages
#' @noRd
get_citations <- function(pkg){
  base_pkgs <- rownames(installed.packages(lib.loc = .Library, priority = "base"))
  pkg <- unique(ifelse(pkg %in% base_pkgs, "base", pkg))
  cits <- lapply(pkg, function(p){
    tryCatch(citation(p), error = function(e){
      warning(sprintf("Skipping %s: %s", p, conditionMessage(e)), call. = FALSE)
      NULL
    })
  })
  names(cits) <- pkg
  Filter(Negate(is.null), cits)
}

#' Save an item to Zotero through the connector
#' @noRd
#' @author Ethan Bass

save_item <- function(zot_item){
  payload <- list(items = list(zot_item))

  response <- httr::POST("http://localhost:23119/connector/saveItems",
                         body = jsonlite::toJSON(payload, auto_unbox = TRUE),
                         httr::add_headers("Content-Type" = "application/json"))
  response
}

#' Get keys of library items of the given types from Zotero's local API
#' @return Character vector of keys from [item_key].
#' @noRd
get_library_keys <- function(item_types){
  unlist(lapply(item_types, function(type){
    keys <- character()
    start <- 0
    repeat {
      response <- httr::GET("http://localhost:23119/api/users/0/items",
                            query = list(itemType = type, format = "json",
                                         limit = 100, start = start))
      httr::stop_for_status(response)
      page <- httr::content(response, "parsed")
      keys <- c(keys, vapply(page, function(x){
        item_key(x$data$itemType, x$data$title, x$data$date)
      }, character(1)))
      start <- start + 100
      if (length(page) < 100) break
    }
    keys
  }))
}

#' Key for matching duplicate items: type, normalized title and year
#' @return `NA` for an untitled item, which never matches.
#' @noRd
item_key <- function(item_type, title, date){
  title <- gsub("<[^>]+>", "", c(title, "")[1])
  title <- tolower(trimws(gsub("[^[:alnum:]]+", " ", title)))
  if (!nzchar(title)) return(NA_character_)
  year <- regmatches(c(date, "")[1], regexpr("[0-9]{4}", c(date, "")[1]))
  paste(item_type, title, c(year, "")[1], sep = "|")
}

#' Check if Zotero is running
#' @noRd
zotero_running <- function() {
  tryCatch({
    response <- httr::GET("http://localhost:23119/connector/ping")
    return(httr::status_code(response) == 200)
  }, error = function(e) FALSE)
}
